def map_transcript_codes(raw_codes: Set[str]) -> Tuple[Set[str], Set[str]]:
    """
    يحوّل مجموعة رموز مستخرجة من السجل إلى رموز الخطة الداخلية عبر TRANSCRIPT_TO_PLAN_CODE.
    يرجع (mapped_codes, unmapped_codes):
      - mapped_codes: الرموز التي أمكن تحويلها لرمز خطة معروف، جاهزة للاستخدام في Student.completed_courses.
      - unmapped_codes: رموز اجتازها الطالب فعلاً في السجل لكن لا يوجد لها تعيين بعد في هذا الملف —
        تُعرض في الواجهة كتنبيه حتى يعرف المستخدم ما ينقص الخريطة، بدل تجاهلها بصمت.
    """
    mapped = set()
    unmapped = set()
    for code in raw_codes:
        plan_code = TRANSCRIPT_TO_PLAN_CODE.get(code)
        if plan_code:
            mapped.add(plan_code)
        else:
            unmapped.add(code)
    return mapped, unmapped